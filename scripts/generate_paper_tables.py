"""
Publication-ready tables from measured results (Phase 11).

Emits, into research/tables/:

    ablation_main.csv / .tex      Model | PSNR | SSIM | LPIPS
    ablation_full.csv / .tex      + Params | FLOPs | Runtime | Peak VRAM
    baseline_detail.csv           per-metric mean/std/min/max for each model

    python scripts/generate_paper_tables.py
    python scripts/generate_paper_tables.py --results-dir results --profile research/tables/profile.json

Sources
-------
metrics            results/<ablation>/summary.json          (evaluate.py)
params / runtime   the same summary.json, plus an optional profile.json from
                   scripts/profile_models.py for FLOPs

MISSING DATA POLICY
-------------------
Every unmeasured cell is rendered as the LaTeX math dash `--` (CSV: `not run`).
Nothing is interpolated, carried across rows, or filled from a different
protocol. A table where an unrun ablation is indistinguishable from a measured
one is fabricated evidence, so the emitted LaTeX also carries a comment listing
exactly which rows are unmeasured.

Bolding: the best MEASURED value per column is bolded, respecting direction
(LPIPS lower is better). With fewer than two measured rows nothing is bolded,
because "best of one" is not a comparison.
"""

import argparse
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from utils.research import (  # noqa: E402
    ABLATION_ORDER, MODEL_LABELS, METRIC_DIRECTION, assert_comparable,
    base_provenance, load_ablation_results,
)

NOT_RUN_CSV = "not run"
NOT_RUN_TEX = "--"


def fmt(v, spec):
    return NOT_RUN_CSV if v is None else format(v, spec)


def human_params(n):
    return NOT_RUN_CSV if n is None else f"{n / 1e6:.2f}M"


def best_index(values: list, direction: str) -> int | None:
    """Index of the best measured value, or None if fewer than two exist."""
    idx = [i for i, v in enumerate(values) if v is not None]
    if len(idx) < 2:
        return None
    return (max(idx, key=lambda i: values[i]) if direction == "higher"
            else min(idx, key=lambda i: values[i]))


def write_csv(path: str, header: list[str], rows: list[list[str]]) -> None:
    import csv
    with io.open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def write_tex(path: str, caption: str, label: str, header: list[str],
              rows: list[list[str]], notes: list[str]) -> None:
    align = "l" + "c" * (len(header) - 1)
    lines = [
        "% Generated by scripts/generate_paper_tables.py -- do not edit by hand.",
        "% Regenerate after any new evaluation; do not fill '--' in manually.",
    ]
    lines += [f"% {n}" for n in notes]
    lines += [
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    with io.open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--results-dir", default="results")
    ap.add_argument("--out-dir", default="research/tables")
    ap.add_argument("--profile", default=None,
                    help="profile.json from scripts/profile_models.py (adds FLOPs)")
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    results = load_ablation_results(args.results_dir)
    protocol = assert_comparable(results)

    profile = {}
    if args.profile and os.path.exists(args.profile):
        with io.open(args.profile, "r", encoding="utf-8") as f:
            profile = {e["ablation"]: e for e in json.load(f).get("models", [])}

    present = [n for n in ABLATION_ORDER if results.get(n)]
    missing = [n for n in ABLATION_ORDER if not results.get(n)]
    print(f"measured: {present or 'none'}")
    print(f"not run : {missing or 'none'}")

    # Column values, None where unmeasured.
    def metric(name, key):
        s = results.get(name)
        m = (s or {}).get("metrics", {}).get(key)
        return None if m is None else float(m["mean"])

    psnr = [metric(n, "psnr") for n in ABLATION_ORDER]
    ssim = [metric(n, "ssim") for n in ABLATION_ORDER]
    lpips = [metric(n, "lpips") for n in ABLATION_ORDER]
    params = [(results[n].get("parameters") if results.get(n)
               else (profile.get(n) or {}).get("params_total")) for n in ABLATION_ORDER]
    runtime = [(results[n].get("mean_inference_s") if results.get(n)
                else (profile.get(n) or {}).get("inference_s")) for n in ABLATION_ORDER]
    vram = [(results[n].get("peak_vram_mb") if results.get(n)
             else (profile.get(n) or {}).get("peak_vram_mb")) for n in ABLATION_ORDER]
    flops = [(profile.get(n) or {}).get("gflops") for n in ABLATION_ORDER]

    proto_txt = (f"{protocol[3]} images, split={protocol[0]}, crop\\_mode={protocol[1]}, "
                 f"crop\\_size={protocol[2]}" if protocol else "no measured results")
    notes = [f"Evaluation protocol: {proto_txt}",
             "'--' means the experiment has not been run; it is NOT a zero or a "
             "carried-over value."]
    if missing:
        notes.append("Unmeasured rows: " + ", ".join(missing))

    # ---- main table --------------------------------------------------------
    b_psnr = best_index(psnr, METRIC_DIRECTION["psnr"])
    b_ssim = best_index(ssim, METRIC_DIRECTION["ssim"])
    b_lpips = best_index(lpips, METRIC_DIRECTION["lpips"])

    def tex_cell(v, spec, is_best):
        if v is None:
            return NOT_RUN_TEX
        s = format(v, spec)
        return rf"\textbf{{{s}}}" if is_best else s

    csv_rows, tex_rows = [], []
    for i, name in enumerate(ABLATION_ORDER):
        label = MODEL_LABELS.get(name, name)
        csv_rows.append([label, fmt(psnr[i], ".3f"), fmt(ssim[i], ".4f"),
                         fmt(lpips[i], ".4f")])
        tex_rows.append([label,
                         tex_cell(psnr[i], ".3f", i == b_psnr),
                         tex_cell(ssim[i], ".4f", i == b_ssim),
                         tex_cell(lpips[i], ".4f", i == b_lpips)])

    header_csv = ["Model", "PSNR (dB)", "SSIM", "LPIPS"]
    header_tex = ["Model", r"PSNR (dB) $\uparrow$", r"SSIM $\uparrow$", r"LPIPS $\downarrow$"]
    write_csv(os.path.join(args.out_dir, "ablation_main.csv"), header_csv, csv_rows)
    write_tex(os.path.join(args.out_dir, "ablation_main.tex"),
              "SRRT ablation study on GoPro. Only measured results are shown; "
              "$--$ marks experiments that have not been run.",
              "tab:ablation_main", header_tex, tex_rows, notes)

    # ---- full table with cost columns --------------------------------------
    header_csv_f = ["Model", "PSNR (dB)", "SSIM", "LPIPS", "Params", "GFLOPs",
                    "Runtime (s/img)", "Peak VRAM (MB)"]
    header_tex_f = ["Model", r"PSNR $\uparrow$", r"SSIM $\uparrow$", r"LPIPS $\downarrow$",
                    "Params", "GFLOPs", "s/img", "VRAM (MB)"]
    csv_rows_f, tex_rows_f = [], []
    for i, name in enumerate(ABLATION_ORDER):
        label = MODEL_LABELS.get(name, name)
        csv_rows_f.append([label, fmt(psnr[i], ".3f"), fmt(ssim[i], ".4f"),
                           fmt(lpips[i], ".4f"), human_params(params[i]),
                           fmt(flops[i], ".1f"), fmt(runtime[i], ".4f"),
                           fmt(vram[i], ".0f")])
        tex_rows_f.append([label,
                           tex_cell(psnr[i], ".3f", i == b_psnr),
                           tex_cell(ssim[i], ".4f", i == b_ssim),
                           tex_cell(lpips[i], ".4f", i == b_lpips),
                           NOT_RUN_TEX if params[i] is None else human_params(params[i]),
                           NOT_RUN_TEX if flops[i] is None else f"{flops[i]:.1f}",
                           NOT_RUN_TEX if runtime[i] is None else f"{runtime[i]:.4f}",
                           NOT_RUN_TEX if vram[i] is None else f"{vram[i]:.0f}"])

    notes_f = notes + [
        "Params/runtime/VRAM come from the same evaluation run as the metrics.",
        "GFLOPs require scripts/profile_models.py --flops; '--' means not measured."]
    write_csv(os.path.join(args.out_dir, "ablation_full.csv"), header_csv_f, csv_rows_f)
    write_tex(os.path.join(args.out_dir, "ablation_full.tex"),
              "SRRT ablation with computational cost. Accuracy gains must be read "
              "against the added cost. $--$ marks unmeasured quantities.",
              "tab:ablation_full", header_tex_f, tex_rows_f, notes_f)

    # ---- per-metric spread -------------------------------------------------
    detail_rows = []
    for name in ABLATION_ORDER:
        s = results.get(name)
        if not s:
            detail_rows.append([MODEL_LABELS.get(name, name), NOT_RUN_CSV] + [NOT_RUN_CSV] * 4)
            continue
        for key in ("psnr", "ssim", "lpips"):
            m = s["metrics"].get(key)
            if not m:
                continue
            detail_rows.append([MODEL_LABELS.get(name, name), key,
                                f"{m['mean']:.6f}", f"{m.get('std', float('nan')):.6f}",
                                f"{m.get('min', float('nan')):.6f}",
                                f"{m.get('max', float('nan')):.6f}"])
    write_csv(os.path.join(args.out_dir, "baseline_detail.csv"),
              ["Model", "Metric", "mean", "std", "min", "max"], detail_rows)

    prov = base_provenance(
        artifact="paper_tables",
        results_dir=os.path.abspath(args.results_dir),
        protocol={"split": protocol[0] if protocol else None,
                  "crop_mode": protocol[1] if protocol else None,
                  "crop_size": protocol[2] if protocol else None,
                  "num_images": protocol[3] if protocol else None},
        measured=present, not_run=missing,
        sources={n: results[n]["_summary_path"] for n in present},
        profile_json=args.profile,
        missing_policy="'--' / 'not run'; never interpolated",
    )
    with io.open(os.path.join(args.out_dir, "tables_provenance.json"), "w",
                 encoding="utf-8") as f:
        json.dump(prov, f, indent=2, default=str)

    for fn in ("ablation_main.csv", "ablation_main.tex", "ablation_full.csv",
               "ablation_full.tex", "baseline_detail.csv", "tables_provenance.json"):
        print(f"wrote {os.path.join(args.out_dir, fn)}")

    print("\n--- ablation_main.tex ---")
    print(io.open(os.path.join(args.out_dir, "ablation_main.tex"), encoding="utf-8").read())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
